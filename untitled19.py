import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.naive_bayes import GaussianNB
from sklearn.metrics import accuracy_score, classification_report

# Load the dataset (corrected file name)
df = pd.read_csv("StudentsPerformance_with_headers.csv")

# Separate input and output
X = df.drop(columns=["STUDENT ID", "GRADE"])
y = df["GRADE"]

# Split into training and testing data
X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# Create and train the model
model = GaussianNB()
model.fit(X_train, y_train)

# Predict grades
y_pred = model.predict(X_test)

# Display results
print("Actual grades:", y_test.tolist())
print("Predicted grades:", y_pred.tolist())
print("Accuracy:", accuracy_score(y_test, y_pred))

print("\nClassification Report:")
print(classification_report(y_test, y_pred, zero_division=0))

import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from sklearn.metrics import accuracy_score, classification_report

# Load the dataset (corrected file name)
df = pd.read_csv("StudentsPerformance_with_headers.csv")

# Separate input and output
X = df.drop(columns=["STUDENT ID", "GRADE"])
y = df["GRADE"]

# Split into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# Standardize the features
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# Create and train the SVM model
model = SVC(kernel="linear")
model.fit(X_train_scaled, y_train)

# Predict student grades
y_pred = model.predict(X_test_scaled)

# Display results
print("Actual grades:", y_test.tolist())
print("Predicted grades:", y_pred.tolist())
print("Accuracy:", accuracy_score(y_test, y_pred))

print("\nClassification Report:")
print(classification_report(y_test, y_pred, zero_division=0))